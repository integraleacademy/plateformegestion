DISTRIBUTEUR_FILE = os.path.join(DATA_DIR, "distributeur.json")

def load_distributeur():
    """Charge le distributeur depuis le fichier JSON, ou crÃ©e une structure par dÃ©faut."""
    default_data = {
        "lignes": [
            {"id": 1, "produits": []},
            {"id": 2, "produits": []},
            {"id": 3, "produits": []},
            {"id": 4, "produits": []},
            {"id": 5, "produits": []}
        ]
    }

    if os.path.exists(DISTRIBUTEUR_FILE):
        try:
            with open(DISTRIBUTEUR_FILE, "r", encoding="utf-8") as f:
                data = json.load(f)
                if isinstance(data, dict) and isinstance(data.get("lignes"), list):
                    return data
        except Exception:
            app.logger.exception("Impossible de lire %s", DISTRIBUTEUR_FILE)

            # Tentative de rÃ©cupÃ©ration: certains fichiers ont du texte parasite
            # autour d'un JSON valide (copier/coller, merge, etc.).
            try:
                with open(DISTRIBUTEUR_FILE, "r", encoding="utf-8") as f:
                    content = f.read()
                start = content.find("{")
                end = content.rfind("}")
                if start != -1 and end != -1 and end > start:
                    recovered = json.loads(content[start:end + 1])
                    if isinstance(recovered, dict) and isinstance(recovered.get("lignes"), list):
                        app.logger.warning("RÃ©cupÃ©ration partielle de %s aprÃ¨s corruption JSON", DISTRIBUTEUR_FILE)
                        return recovered
            except Exception:
                app.logger.exception("RÃ©cupÃ©ration impossible pour %s", DISTRIBUTEUR_FILE)

    return default_data

def save_distributeur(data):
    """Sauvegarde complÃ¨te du distributeur."""
    with open(DISTRIBUTEUR_FILE, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)



